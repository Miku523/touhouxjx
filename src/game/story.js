/* ------------------------------------------------------------------
 * 取词辅助：剧情数据按主角分线，调用方不必关心内部结构。
 * ------------------------------------------------------------------ */
export function routeOf(char) {
  return char === 'marisa' ? 'marisa' : 'reimu';
}

export function openingFor(char) {
  return STORY.opening[routeOf(char)] || STORY.opening.reimu;
}

export function stageStoryFor(char, key) {
  return STORY.stages[key]?.[routeOf(char)] || {};
}

export function extraIntroFor(char) {
  return STORY.extra.intro[routeOf(char)] || STORY.extra.intro.reimu;
}

/**
 * EXTRA 连环战的战前台词。
 * index: 0=咲夜初战 1=蕾米莉亚 2=咲夜再登场 3=芙兰朵露（终盘）。
 * 越界或缺线一律返回 []，调用方可以无脑播。
 * @param {string} char 'reimu' | 'marisa'
 * @param {number} index 0 ~ extraChainLength()-1
 * @returns {Array<{who:string,text:string,mood?:string}>}
 */
export function extraChainPreFor(char, index) {
  const arr = STORY.extra.chainPre[index];
  return (arr && (arr[routeOf(char)] || arr.reimu)) || [];
}

/** EXTRA 连环战的换气短过场：0=咲夜初战退场 1=蕾米败 2=咲夜二次退场（缺失返回 []） */
export function extraChainPostFor(char, index) {
  const arr = STORY.extra.chainPost[index];
  return (arr && (arr[routeOf(char)] || arr.reimu)) || [];
}

/** EXTRA 连环战的段数（四场 Boss），main.js 可用来限位遍历 */
export function extraChainLength() {
  return STORY.extra.chainPre.length;
}

export function extraPreFor(char) {
  // 兼容旧调用：EXTRA 的终盘战前段即 chainPre 第 4 段（芙兰朵露登场前）。
  return extraChainPreFor(char, 3);
}

export function extraPostFor(char) {
  return STORY.extra.postBoss[routeOf(char)] || STORY.extra.postBoss.reimu;
}

/**
 * 中途 Boss 的剧情段：先取自机路线的同名键，没有再退回关卡层级（不分线的公共版本）。
 * 现在只有 STAGE5 的魂魄妖梦：STORY.stages.stage5.youmuPre / youmuPost。
 * 取不到一律返回空数组，调用方（main.js）可以无脑播。
 * @param {string} char 'reimu' | 'marisa'
 * @param {string} key  关卡键，如 'stage5'
 * @param {'pre'|'post'} phase
 * @returns {Array<{who:string,text:string,mood?:string}>}
 */
export function midbossStoryFor(char, key, phase) {
  const st = STORY.stages[key];
  if (!st) return [];
  const field = phase === 'post' ? 'youmuPost' : 'youmuPre';
  const route = st[routeOf(char)];
  const own = route && route[field];
  if (Array.isArray(own) && own.length) return own;
  return Array.isArray(st[field]) ? st[field] : [];
}

/** 中途 Boss 战前对话（缺失返回 []） */
export function midbossPreFor(char, key) {
  return midbossStoryFor(char, key, 'pre');
}

/** 中途 Boss 战后对话（缺失返回 []） */
export function midbossPostFor(char, key) {
  return midbossStoryFor(char, key, 'post');
}
