/** 贝斯：0–1 小节四分音符根音/五度铺陈，2 小节起换成推动感强的八分型 */
function buildTitleBass() {
  const out = [];
  const EIGHTH = [0, 0, 7, 0, 0, 7, 0, 12]; // 根、根、五、根、根、五、根、高八度
  const QUARTER = [0, 7, 0, 7];
  for (let b = 0; b < TITLE_BARS; b++) {
    const root = TITLE_ROOT[TITLE_CHORDS[b]];
    const vel = b < 2 ? 86 : b < 8 ? 96 : b < 24 ? 100 : 104;
    if (b < 2) {
      for (let i = 0; i < 4; i++) {
        out.push([r6(b * TBAR + i * 4 * T16), root + QUARTER[i], r6(0.35), vel]);
      }
    } else {
      for (let i = 0; i < 8; i++) {
        out.push([r6(b * TBAR + i * 2 * T16), root + EIGHTH[i], r6(0.18), vel]);
      }
    }
  }
  return out;
}

/** 琶音伴奏：0–3 小节八分、4 小节起十六分；四音型「和弦三音 + 根音高八度」 */
function buildTitleArp() {
  const out = [];
  for (let b = 0; b < TITLE_BARS; b++) {
    const tones = TITLE_ARP[TITLE_CHORDS[b]];
    const slow = b < 4;
    const perBar = slow ? 8 : 16;
    const stepDur = slow ? T16 * 2 : T16;
    const dur = slow ? 0.18 : 0.09;
    const vel = b < 4 ? 46 : b < 8 ? 58 : b < 24 ? 62 : 66;
    for (let i = 0; i < perBar; i++) {
      const k = i % 4;
      const midi = k === 3 ? tones[0] + 12 : tones[k];
      out.push([r6(b * TBAR + i * stepDur), midi, dur, vel]);
    }
  }
  return out;
}

