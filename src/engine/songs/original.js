/** 长音低音：每小节一个整小节根音，奇数小节在第 4 拍补一个五度做推进 */
function buildGoBass() {
  const out = [];
  for (let b = 0; b < GO_BARS; b++) {
    const chord = GO_CHORDS[b];
    const root = GO_ROOT[chord];
    out.push([r6(b * GBAR), root, r6(11 * G16), b === 0 ? 68 : 72]);
    if (b % 2 === 1) {
      out.push([r6(b * GBAR + 12 * G16), GO_FIFTH[chord], r6(3.5 * G16), 44]);
    }
  }
  return out;
}

/** 极轻心跳鼓：前两小节完全留白，末小节只留一记底鼓 */
function buildGoDrums() {
  const list = [];
  for (let b = 2; b < 9; b++) {
    list.push([r6(b * GBAR), 0, b === 8 ? 36 : 46]);
    list.push([r6(b * GBAR + 8 * G16), 0, 34]);
    if (b >= 4) list.push([r6(b * GBAR + 12 * G16), 2, 18]);
  }
  list.push([r6(4 * GBAR), 4, 28]); // 唯一的镲，落在乐句转折处
  list.push([r6(9 * GBAR), 0, 30]);
  list.sort((a, b) => a[0] - b[0] || a[1] - b[1]);
  return list;
}

