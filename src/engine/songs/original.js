/** 音名 → MIDI 音高：'D5' / 'Bb2' / 'F#4' */
const BASE = { C: 0, D: 2, E: 4, F: 5, G: 7, A: 9, B: 11 };

function n(name) {
  const m = /^([A-G])([#b]?)(-?\d+)$/.exec(name);
  if (!m) throw new Error('非法音名: ' + name);
  const acc = m[2] === '#' ? 1 : m[2] === 'b' ? -1 : 0;
  return 12 * (Number(m[3]) + 1) + BASE[m[1]] + acc;
}

/** 时间保留 6 位小数，避免浮点尾巴 */
const r6 = (x) => Math.round(x * 1e6) / 1e6;

/**
 * 把「小节 / 十六分格 / 音名 / 时值格 / 力度」的行表展开成音符数组。
 * rows: [bar, step16, 'D5', durSteps, vel]
 * 时值用「格子终点的舍入值 − 起点舍入值」算，保证首尾相接的音不会因浮点尾巴叠一起。
 */
function buildNotes(rows, step16) {
  const out = [];
  for (const [bar, st, name, ds, vel] of rows) {
    const base = bar * 16 + st;
    const t = r6(base * step16);
    const end = r6((base + ds) * step16);
    out.push([t, n(name), r6(end - t), vel]);
  }
  return out;
}

