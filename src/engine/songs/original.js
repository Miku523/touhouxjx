/** 尾句从 20 小节起逐小节整体渐弱 */
const fadeFactor = (b) => (b < 20 ? 1 : Math.max(0.5, 1 - (b - 20) * 0.075));

/** 三角波低音：每小节两个长音（根、根），个别小节末拍补五度 */
function buildEdBass() {
  const out = [];
  for (let b = 0; b < ED_BARS; b++) {
    const chord = ED_CHORDS[b];
    const root = ED_ROOT[chord];
    const f = fadeFactor(b);
    const v1 = Math.round((b < 4 ? 78 : 88) * f);
    const v2 = Math.round((b < 4 ? 70 : 80) * f);
    // 补五度的那一小节，第二个根音缩短，避免低音自己和自己叠音
    const withFifth = b >= 12 && b % 4 === 3;
    out.push([r6(b * EBAR), root, r6(7 * E16), v1]);
    out.push([r6(b * EBAR + 8 * E16), root, r6((withFifth ? 4 : 7) * E16), v2]);
    if (withFifth) {
      out.push([r6(b * EBAR + 12 * E16), ED_FIFTH[chord], r6(3 * E16), Math.round(58 * f)]);
    }
  }
  return out;
}

/** 十六分琶音铺底：0–1 小节八分进入，之后全十六分；「上–上–上–回」柔和四音型 */
function buildEdArp() {
  const out = [];
  for (let b = 0; b < ED_BARS; b++) {
    const tones = ED_ARP[ED_CHORDS[b]];
    const f = fadeFactor(b);
    const slow = b < 2;
    const perBar = slow ? 8 : 16;
    const stepDur = slow ? E16 * 2 : E16;
    for (let i = 0; i < perBar; i++) {
      const k = [0, 1, 2, 1][i % 4];
      out.push([
        r6(b * EBAR + i * stepDur),
        tones[k],
        0.13,
        Math.round((b < 4 ? 42 : b < 20 ? 50 : 50) * f),
      ]);
    }
  }
  return out;
}

/** 轻鼓：0–3 小节只有心跳，4 小节起加软军鼓与八分踩镲，尾句跟着渐弱 */
function buildEdDrums() {
  const list = [];
  for (let b = 0; b < ED_BARS; b++) {
    const f = fadeFactor(b);
    const soft = b < 4;
    list.push([r6(b * EBAR), 0, Math.round((soft ? 52 : 60) * f)]);
    list.push([r6(b * EBAR + 8 * E16), 0, Math.round((soft ? 42 : 50) * f)]);
    if (!soft) {
      list.push([r6(b * EBAR + 4 * E16), 1, Math.round(30 * f)]);
      list.push([r6(b * EBAR + 12 * E16), 1, Math.round(34 * f)]);
      for (let i = 1; i < 8; i += 2) {
        list.push([r6(b * EBAR + i * 2 * E16), 2, Math.round(24 * f)]);
      }
    } else if (b >= 2) {
      list.push([r6(b * EBAR + 8 * E16), 2, 18]);
    }
  }
  for (const [b, vel] of [[4, 40], [20, 34]]) {
    list.push([r6(b * EBAR), 4, vel]);
  }
  list.sort((a, b) => a[0] - b[0] || a[1] - b[1]);
  return list;
}

