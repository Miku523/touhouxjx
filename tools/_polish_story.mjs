function apply(file, pairs) {
  let text = fs.readFileSync(file, 'utf8');
  const problems = [];
  const applied = [];
  for (const [oldText, newText, label] of pairs) {
    const count = text.split(oldText).length - 1;
    if (count !== 1) {
      problems.push(`${label}: expected 1, found ${count}`);
      continue;
    }
    text = text.replace(oldText, newText);
    applied.push(label);
  }
  if (problems.length) {
    console.error(`FAIL ${file}\n  ` + problems.join('\n  '));
    process.exitCode = 1;
    return;
  }
  fs.writeFileSync(file, text);
  console.log(`OK ${file}: ${applied.length} replacements`);
}

